// lib/backend/groups.ts
//
// Group create/join orchestration over the Backend_Client collection accessors
// (Req 4.1–4.10). The screens (`app/create-group`, `app/join-group`) own only
// their form state, client-side gating (see `validation.ts`), and navigation;
// the multi-step backend sequencing lives here so it can be unit-tested without
// a React/DOM harness.
//
// Each function returns a structured result describing what the screen should
// do next (navigate to a group, or show a message) instead of performing
// navigation itself, keeping this module free of Next.js router and UI concerns.

import {
  groupsCollection,
  groupMembersCollection,
  readingSessionsCollection,
  progressCollection,
  normalizeError,
} from "./client";

/** A dependency bundle so tests can supply fakes for the collection accessors. */
export interface GroupBackend {
  groups: () => ReturnType<typeof groupsCollection>;
  groupMembers: () => ReturnType<typeof groupMembersCollection>;
  readingSessions: () => ReturnType<typeof readingSessionsCollection>;
  progress: () => ReturnType<typeof progressCollection>;
}

/** The live backend wiring used by the screens. */
export const liveGroupBackend: GroupBackend = {
  groups: groupsCollection,
  groupMembers: groupMembersCollection,
  readingSessions: readingSessionsCollection,
  progress: progressCollection,
};

/**
 * The outcome of a create/join operation. On success `groupId` names the group
 * the screen should navigate to (Req 4.5, 4.9); on failure `message` is the
 * text to display and the screen MUST NOT navigate (Req 4.3, 4.8).
 */
export type GroupOpResult =
  | { ok: true; groupId: string }
  | { ok: false; message: string };

/**
 * Create a group and record the creating user as its first member (Req 4.1).
 * The invite code is generated by the backend's create hook (unique, 6–32
 * chars); the client never supplies it (Req 4.2). On any backend failure a
 * message is returned and no group id is produced, so the screen does not
 * navigate (Req 4.3).
 *
 * Name trimming/emptiness is gated in the screen before this runs (Req 4.4);
 * the trimmed values are passed in here.
 */
export async function createGroup(
  userId: string,
  groupName: string,
  displayName: string,
  backend: GroupBackend = liveGroupBackend,
): Promise<GroupOpResult> {
  try {
    const group = await backend.groups().create({ name: groupName.trim() });

    await backend.groupMembers().create({
      user: userId,
      group: group.id,
      display_name: displayName.trim(),
    });

    return { ok: true, groupId: group.id };
  } catch (err) {
    return {
      ok: false,
      message: normalizeError(err).message || "Could not create group.",
    };
  }
}

/**
 * Join a group by invite code (Req 4.6–4.10):
 *   - Look up the group by code; no match → a "no group found" message and no
 *     membership is created (Req 4.8).
 *   - If the user is already a member, do NOT create a duplicate membership and
 *     still navigate to the group (Req 4.9).
 *   - Otherwise add the membership (Req 4.6) and, if the group has an active
 *     reading session, seed a zeroed progress record for the new member
 *     (Req 4.10).
 *
 * Display-name trimming/emptiness is gated in the screen before this runs
 * (Req 4.7); the trimmed value is passed in here.
 */
export async function joinGroup(
  userId: string,
  inviteCode: string,
  displayName: string,
  backend: GroupBackend = liveGroupBackend,
): Promise<GroupOpResult> {
  try {
    // Invite codes are stored uppercase; normalize the entered code so a
    // case-insensitive match still resolves (Req 4.6, 4.8).
    const code = inviteCode.trim().toUpperCase();

    let group;
    try {
      group = await backend.groups().getFirstListItem(`invite_code = "${code}"`);
    } catch (lookupErr) {
      if (normalizeError(lookupErr).kind === "not_found") {
        return { ok: false, message: "No group found with that invite code." };
      }
      throw lookupErr;
    }

    // Already a member? Do not create a duplicate (the `(user, group)` unique
    // index would reject it) and still navigate (Req 4.9).
    const existingMembership = await backend
      .groupMembers()
      .getFirstListItem(`user = "${userId}" && group = "${group.id}"`)
      .catch((membershipErr) => {
        if (normalizeError(membershipErr).kind === "not_found") {
          return null;
        }
        throw membershipErr;
      });

    if (existingMembership) {
      return { ok: true, groupId: group.id };
    }

    await backend.groupMembers().create({
      user: userId,
      group: group.id,
      display_name: displayName.trim(),
    });

    // Seed a zeroed progress record when the group has an active session
    // (Req 4.10).
    const activeSession = await backend
      .readingSessions()
      .getFirstListItem(`group = "${group.id}" && is_active = true`)
      .catch((sessionErr) => {
        if (normalizeError(sessionErr).kind === "not_found") {
          return null;
        }
        throw sessionErr;
      });

    if (activeSession) {
      await backend.progress().create({
        reading_session: activeSession.id,
        user: userId,
        chapter_completed: 0,
      });
    }

    return { ok: true, groupId: group.id };
  } catch (err) {
    return {
      ok: false,
      message: normalizeError(err).message || "Could not join group.",
    };
  }
}
